# Faça um programa que leia algo pelo teclado e mostre na tela o seu tipo primitivo e todas as informações possíveis sobre ele.

v = input('Digite algo ')
print(type(v))
print(v.isalnum())
print(v.isalpha())
print(v.isascii())
print(v.isdecimal())
print(v.isdigit())
print(v.isidentifier())
print(v.islower())
print(v.isprintable())
print(v.istitle())
print(v.isupper())
print(v.isspace())

